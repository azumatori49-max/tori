/** 朝礼原稿（1回/日）。fallbackLevel: 'full'|'no_sales'|'none'（§8-1 欠測フォールバック） */
function buildBriefPrompt_(data) {
  const user = [
    '本日の朝礼原稿（音声で約60〜90秒、モニター表示兼用）を作成してください。',
    '構成: 挨拶 → 昨日の結果（欠測時は触れない）→ 本日の見込みと重点行動1つ → 感謝・称賛。',
    '全体の3割は感謝と称賛に割り当てる。称賛は個人名でなくチームや行動に向ける。',
    '',
    '# 入力データ',
    JSON.stringify(data, null, 2),
    '',
    '# 欠測時の扱い',
    'fallback_level が no_sales のとき: 数字に触れず、重点行動と注意事項のみ。',
    'fallback_level が none のとき: 定型の朝礼とし、本日の数値は未連携ですと明示する。',
    '',
    '# 出力（JSONのみ）',
    '{"speech": "音声用原稿（記号なしの話し言葉）", "display": "モニター表示用の短い要約（80字以内）"}'
  ].join('\n');
  return { system: SYSTEM_COMMON, user: user };
}

/** 状況コメント（中間チェック等）。店長向けの情報提供として書かせる */
function buildCheckPrompt_(data) {
  const user = [
    '店長向けの状況コメントを作成してください。宛先は店長のみ（スタッフには届かない）。',
    '状態コードとルールの intent に沿い、事実 → 解釈（断定しない）→ 店長への判断依頼、の順で3文以内。',
    data.flags && data.flags.no_blame
      ? '★乖離が大きいため外部要因の可能性があります。原因の断定を一切せず、「原因の確認をお願いします」で止めてください。'
      : '',
    '',
    '# 入力データ',
    JSON.stringify(data, null, 2),
    '',
    '# 出力（JSONのみ）',
    '{"display": "モニター/LINE表示用コメント（120字以内）"}'
  ].join('\n');
  return { system: SYSTEM_COMMON, user: user };
}

/** 日次振り返り（1回/日、閉店後） */
function buildReviewPrompt_(data) {
  const user = [
    '本日の振り返りを作成してください。宛先は店長。',
    '構成: 結果の要約（数字1つ以上）→ 判定結果の説明 → 明日に向けた提案1つ（判断は店長に返す）→ 労いの一言。',
    '',
    '# 入力データ',
    JSON.stringify(data, null, 2),
    '',
    '# 出力（JSONのみ）',
    '{"display": "振り返り本文（300字以内）"}'
  ].join('\n');
  return { system: SYSTEM_COMMON, user: user };
}

