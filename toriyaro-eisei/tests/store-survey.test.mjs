import assert from 'node:assert/strict';
import { storeSurveyUrl, connectStoreSurvey, storeSurveyAccessUrl, clearStoreSurveySessions } from '../src/lib/storeSurvey.ts';
assert.equal(storeSurveyUrl('store_0a122e63'), 'https://toriyaro-okayama-survey.azumatori49.chatgpt.site/staff');
assert.equal(storeSurveyUrl('store_8076d145'), 'https://toriyaro-chibachuo-survey.azumatori49.chatgpt.site/staff');
assert.equal(storeSurveyUrl('store_4683aab2'), 'https://toriyaro-nagasaki-survey.azumatori49.chatgpt.site/staff');
assert.equal(storeSurveyUrl('store_e13bfd3d'), 'https://toriyaro-surveys.azumatori49.chatgpt.site/staff?store=d-32', 'Chiba station east has its own viewer');
assert.equal(storeSurveyUrl('store_1b9f586d'), 'https://toriyaro-surveys.azumatori49.chatgpt.site/staff?store=izakara-machida');
assert.equal(storeSurveyUrl('store_d7f97d5c'), 'https://toriyaro-surveys.azumatori49.chatgpt.site/staff?store=sushitori-shimbashi');
assert.equal(storeSurveyUrl('store_e16746f6'), 'https://toriyaro-surveys.azumatori49.chatgpt.site/staff?store=sushitori-kitasenju');
assert.equal(storeSurveyUrl('store_4187419d'), 'https://toriyaro-surveys.azumatori49.chatgpt.site/staff?store=d-4');
assert.equal(storeSurveyUrl('store_f1b8e7de'), 'https://toriyaro-surveys.azumatori49.chatgpt.site/staff?store=marusuke-machida');
assert.equal(storeSurveyUrl('store_b1a0c9b7'), 'https://toriyaro-surveys.azumatori49.chatgpt.site/staff?store=yakutoriya-soka');
assert.equal(storeSurveyUrl('store_0993469b'), 'https://toriyaro-surveys.azumatori49.chatgpt.site/staff?store=d-16', 'The existing Machida viewer remains separate');
assert.equal(storeSurveyUrl('constructor'), null);
assert.equal(storeSurveyUrl('unknown'), null, 'Unconfigured stores must not open another store survey');
const saved = new Map();
globalThis.window = { localStorage: { getItem: k => saved.get(k) ?? null, setItem: (k, v) => saved.set(k, v), removeItem: k => saved.delete(k) } };
const key = 'store_0a122e63';
let calls = 0;
const fetcher = async (url, options) => {
  calls++;
  assert.equal(url.href, 'https://toriyaro-okayama-survey.azumatori49.chatgpt.site/api/store-session');
  assert.deepEqual(JSON.parse(options.body), { storeKey: key, password: 'fixture-password', firebaseIdToken: 'fixture-firebase-token' });
  return Response.json({ token: 'fixture.signature', expiresAt: Date.now() + 60000 });
};
assert.equal(storeSurveyAccessUrl(key), null);
await connectStoreSurvey(key, 'fixture-password', 'fixture-firebase-token', fetcher);
assert.equal(storeSurveyAccessUrl(key), storeSurveyUrl(key) + '#access=fixture.signature');
assert.equal(storeSurveyAccessUrl('store_8076d145'), null);
assert.equal(storeSurveyAccessUrl('store_4683aab2'), null, 'Okayama session must not open Nagasaki responses');
assert.ok(!JSON.stringify([...saved.values()]).includes('fixture-password'));
assert.ok(!JSON.stringify([...saved.values()]).includes('fixture-firebase-token'));
await connectStoreSurvey('unknown', 'fixture-password', 'fixture-firebase-token', fetcher);
assert.equal(calls, 1);
saved.set('toriyaro-eisei.survey-session.' + key, JSON.stringify({ token: 'fixture.signature', expiresAt: 1 }));
assert.equal(storeSurveyAccessUrl(key), null);
await connectStoreSurvey(key, 'fixture-password', 'fixture-firebase-token', fetcher);
clearStoreSurveySessions();
assert.equal(storeSurveyAccessUrl(key), null);
assert.equal(saved.size, 0);
await assert.rejects(connectStoreSurvey(key, 'fixture-password', 'fixture-firebase-token', async () => Response.json({ error: 'denied' }, { status: 401 })));
assert.equal(storeSurveyAccessUrl(key), null);
const centralKey = 'store_e13bfd3d';
await connectStoreSurvey(centralKey, 'fixture-password', 'fixture-firebase-token', async (url, options) => {
  assert.equal(url.href, 'https://toriyaro-surveys.azumatori49.chatgpt.site/api/store-session');
  assert.equal(JSON.parse(options.body).storeKey, centralKey);
  return Response.json({ token: 'central.signature', expiresAt: Date.now() + 60000 });
});
assert.equal(storeSurveyAccessUrl(centralKey), storeSurveyUrl(centralKey) + '#access=central.signature');
assert.equal(storeSurveyAccessUrl(key), null);
clearStoreSurveySessions();
assert.equal(storeSurveyAccessUrl(centralKey), null);
console.log('Store mapping, seamless login handoff, expiry, credential storage and logout clearing passed.');
